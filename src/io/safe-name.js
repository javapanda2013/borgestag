// BorgesTag 共通：タグ名などをファイル名・フォルダ名に使うための変換（GROUP-168、v1.50.13）
//
// background（ファイル名へのタグ付与）／ settings（外部取り込みのタグ付与・タグ名でフォルダ作成）／
// modal（タグ名でフォルダ作成）が同じ規則を使うよう 1 本化する。classic script で window.BTSafeName を公開。
//
// Windows で使えない 9 文字（\ / : * ? " < > |）は削除せず、対応する全角文字へ置き換える。
// - 削除すると「A/B」が「AB」になり、ファイル名からのタグ復元（NFKC 正規化で照合）で元のタグに一致しない。
//   全角 9 文字はいずれも NFKC で元の半角に戻るため、置換なら復元が一致する。
// - フォルダ作成で「/」「\」をそのまま渡すとパスの区切りとして扱われ、名前が途中で切れる。

"use strict";

(function () {
  const FULLWIDTH = {
    "\\": "＼", "/": "／", ":": "：", "*": "＊", "?": "？",
    "\"": "＂", "<": "＜", ">": "＞", "|": "｜",
  };

  /**
   * ファイル名・フォルダ名として使える文字列へ変換する。
   * - Windows 禁止文字 9 種 → 全角
   * - 制御文字（\x00-\x1f）→ 除去
   * - 末尾の空白・ドット（Windows で無効）→ 除去
   * 結果が空文字になりうるため、呼び出し側で空を弾くこと。
   */
  function toSafeName(s) {
    return String(s ?? "")
      .replace(/[\\/:*?"<>|]/g, (c) => FULLWIDTH[c])
      .replace(/[\x00-\x1f]/g, "")
      .replace(/[\s.]+$/, "")
      .trim();
  }

  window.BTSafeName = { toSafeName };
})();
